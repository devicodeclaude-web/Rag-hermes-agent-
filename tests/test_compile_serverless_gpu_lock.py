from __future__ import annotations

import hashlib
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

from scripts import compile_serverless_gpu_lock as compiler


EXPECTED_TORCH = (
    "torch @ https://download-r2.pytorch.org/whl/cu128/"
    "torch-2.8.0%2Bcu128-cp312-cp312-manylinux_2_28_x86_64.whl"
    "#sha256=4354fc05bb79b208d6995a04ca1ceef6a9547b1c4334435574353d381c55087c"
)
HASH = "a" * 64


def write_valid_input_tree(root: Path) -> Path:
    source = root / "requirements-serverless-gpu.in"
    (root / "requirements-gpu.in").write_text(
        "FlagEmbedding==1.3.5\n"
        "huggingface_hub==0.34.4\n"
        "transformers==4.57.6\n",
        encoding="utf-8",
    )
    (root / "requirements-serverless.in").write_text(
        "runpod==1.12.0\n", encoding="utf-8"
    )
    source.write_text(
        "-r requirements-gpu.in\n"
        "-r requirements-serverless.in\n"
        f"{EXPECTED_TORCH}\n",
        encoding="utf-8",
    )
    return source


def valid_compiled_lock() -> str:
    required = {
        "flagembedding": "1.3.5",
        "huggingface-hub": "0.34.4",
        "nvidia-cublas-cu12": "12.8.4.1",
        "nvidia-cuda-runtime-cu12": "12.8.90",
        "runpod": "1.12.0",
        "transformers": "4.57.6",
        "triton": "3.4.0",
    }
    while len(required) < compiler.EXPECTED_COMPILED_PACKAGE_COUNT:
        required[f"fixture-package-{len(required):03d}"] = "1.0.0"
    body = "\n".join(
        f"{name}=={version} \\\n    --hash=sha256:{HASH}"
        for name, version in sorted(required.items())
    )
    return (
        "# This file was autogenerated by uv via the following command:\n"
        f"#    {compiler.COMPILE_COMMAND}\n"
        "--index-url https://pypi.org/simple\n"
        f"{body}\n"
    )


def real_compiled_lock() -> str:
    return "\n".join(
        line
        for line in compiler.OUTPUT.read_text(encoding="utf-8").splitlines()
        if line != compiler.EXPECTED_TORCH_REQUIREMENT
    ) + "\n"


class TorchRequirementValidationTests(unittest.TestCase):
    def test_accepts_only_the_exact_torch_requirement(self):
        with tempfile.TemporaryDirectory() as directory:
            source = write_valid_input_tree(Path(directory))
            self.assertEqual(compiler._torch_requirement(source), EXPECTED_TORCH)

    def test_rejects_unapproved_top_level_or_included_requirements(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = write_valid_input_tree(root)
            mutations = (
                (source, source.read_text(encoding="utf-8") + "evil==1\n"),
                (
                    root / "requirements-gpu.in",
                    "FlagEmbedding==1.3.5\n"
                    "--extra-index-url https://evil.invalid/simple\n",
                ),
                (
                    root / "requirements-serverless.in",
                    "runpod==1.12.0\nevil==1\n",
                ),
            )
            for path, payload in mutations:
                with self.subTest(path=path.name):
                    write_valid_input_tree(root)
                    path.write_text(payload, encoding="utf-8")
                    with self.assertRaises(RuntimeError):
                        compiler._torch_requirement(source)

    def test_rejects_malformed_or_unapproved_torch_requirements(self):
        bad_requirements = [
            EXPECTED_TORCH.replace(compiler.TORCH_SHA256, ""),
            EXPECTED_TORCH.replace(compiler.TORCH_SHA256, "g" * 64),
            EXPECTED_TORCH.replace(compiler.TORCH_SHA256, "a" * 63),
            EXPECTED_TORCH + "&sha256=" + compiler.TORCH_SHA256,
            EXPECTED_TORCH.replace("torch-2.8.0%2Bcu128", "torch-2.8.1%2Bcu128"),
        ]
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for requirement in bad_requirements:
                with self.subTest(requirement=requirement):
                    source = write_valid_input_tree(root)
                    source.write_text(
                        "-r requirements-gpu.in\n"
                        "-r requirements-serverless.in\n"
                        f"{requirement}\n",
                        encoding="utf-8",
                    )
                    with self.assertRaises(RuntimeError):
                        compiler._torch_requirement(source)


class LockValidationTests(unittest.TestCase):
    def test_rejects_empty_incomplete_unhashed_or_duplicate_output(self):
        valid = valid_compiled_lock()
        expected_graph = compiler._package_graph_sha256(compiler._package_blocks(valid))
        cases = {
            "empty": "",
            "incomplete": valid.replace(
                "flagembedding==1.3.5 \\\n    --hash=sha256:" + HASH + "\n",
                "",
            ),
            "unhashed": valid.replace("    --hash=sha256:" + HASH, "", 1),
            "duplicate": valid + "runpod==1.12.0 \\\n    --hash=sha256:" + HASH + "\n",
            "unexpected_url": valid + "evil @ https://example.invalid/evil.whl#sha256=" + HASH + "\n",
            "unrecognized_requirement": valid + "evil>=1\n",
            "conditional_requirement": valid.replace(
                "runpod==1.12.0 " + "\\",
                'runpod==1.12.0 ; python_version < "0" ' + "\\",
            ),
            "requirement_suffix": valid.replace(
                "runpod==1.12.0 " + "\\",
                "runpod==1.12.0 GARBAGE " + "\\",
            ),
            "hash_suffix": valid.replace(
                "    --hash=sha256:" + HASH,
                "    --hash=sha256:" + HASH + " GARBAGE",
                1,
            ),
            "triple_equal": valid.replace(
                "runpod==1.12.0 " + "\\", "runpod===1.12.0 " + "\\"
            ),
            "wildcard_version": valid.replace(
                "runpod==1.12.0 " + "\\", "runpod==1.* " + "\\"
            ),
            "combined_constraint": valid.replace(
                "runpod==1.12.0 " + "\\", "runpod==1.12.0,>=1 " + "\\"
            ),
            "non_sentinel_triple_equal": valid.replace(
                "fixture-package-007==1.0.0 " + "\\",
                "fixture-package-007===1.0.0 " + "\\",
            ),
            "non_sentinel_wildcard": valid.replace(
                "fixture-package-007==1.0.0 " + "\\",
                "fixture-package-007==1.* " + "\\",
            ),
            "non_sentinel_combined_constraint": valid.replace(
                "fixture-package-007==1.0.0 " + "\\",
                "fixture-package-007==1.0.0,>=1 " + "\\",
            ),
            "invalid_pep440_version": valid.replace(
                "fixture-package-007==1.0.0 " + "\\",
                "fixture-package-007==1!! " + "\\",
            ),
            "hash_after_terminal_hash": valid.replace(
                "    --hash=sha256:" + HASH + "\n",
                "    --hash=sha256:"
                + HASH
                + "\n    --hash=sha256:"
                + ("c" * 64)
                + "\n",
                1,
            ),
            "continued_last_hash": valid.replace(
                "    --hash=sha256:" + HASH + "\n",
                "    --hash=sha256:" + HASH + " \\\n",
                1,
            ),
            "orphan_hash": valid.replace(
                "--index-url https://pypi.org/simple\n",
                "--index-url https://pypi.org/simple\n"
                + "    --hash=sha256:"
                + HASH
                + "\n",
            ),
        }
        for name, payload in cases.items():
            with self.subTest(name=name):
                with self.assertRaises(RuntimeError):
                    compiler.validate_registry_lock(
                        payload,
                        compile_command=compiler.COMPILE_COMMAND,
                        expected_package_count=compiler.EXPECTED_COMPILED_PACKAGE_COUNT,
                        required_versions=compiler.REQUIRED_COMPILED_VERSIONS,
                        expected_graph_sha256=expected_graph,
                    )

    def test_accepts_complete_hash_pinned_pypi_output(self):
        compiler._validate_compiled_lock(real_compiled_lock())

    def test_rejects_one_for_one_transitive_package_substitution(self):
        compiled = real_compiled_lock()
        tampered = compiled.replace("accelerate==1.15.0 \\", "attacker-payload==9.9.9 \\")
        self.assertNotEqual(tampered, compiled)
        with self.assertRaises(RuntimeError):
            compiler._validate_compiled_lock(tampered)

    def test_rejects_hash_substitution_with_unchanged_package_graph(self):
        compiled = real_compiled_lock()
        marker = "--hash=sha256:"
        position = compiled.index(marker) + len(marker)
        replacement = "f" if compiled[position] != "f" else "e"
        tampered = compiled[:position] + replacement + compiled[position + 1 :]
        self.assertNotEqual(tampered, compiled)
        with self.assertRaises(RuntimeError):
            compiler._validate_compiled_lock(tampered)

    def test_final_lock_rejects_torch_inside_a_package_hash_sequence(self):
        compiled = real_compiled_lock()
        first_hash = compiled.index("    --hash=sha256:")
        tampered = (
            compiled[:first_hash]
            + compiler.EXPECTED_TORCH_REQUIREMENT
            + "\n"
            + compiled[first_hash:]
        )
        self.assertNotEqual(tampered.splitlines()[-1], compiler.EXPECTED_TORCH_REQUIREMENT)
        with self.assertRaises(RuntimeError):
            compiler._validate_final_lock(tampered, compiler.EXPECTED_TORCH_REQUIREMENT)

    def test_final_lock_is_bound_to_its_complete_content_digest(self):
        final = compiler.OUTPUT.read_text(encoding="utf-8")
        self.assertEqual(
            compiler.EXPECTED_FINAL_CONTENT_SHA256,
            hashlib.sha256(final.encode("utf-8")).hexdigest(),
        )
        with patch.object(compiler, "EXPECTED_FINAL_CONTENT_SHA256", "0" * 64):
            with self.assertRaises(RuntimeError):
                compiler._validate_final_lock(final, compiler.EXPECTED_TORCH_REQUIREMENT)


class GeneratorIsolationTests(unittest.TestCase):
    def test_compile_isolates_indexes_and_publishes_valid_lock_atomically(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = write_valid_input_tree(root)
            output = root / "requirements.lock"
            observed_command: list[str] = []
            observed_env: dict[str, str] = {}
            observed_inputs: dict[str, list[str]] = {}

            def fake_run(command, **kwargs):
                observed_command.extend(command)
                observed_env.update(kwargs["env"])
                source.write_text("evil==1\n", encoding="utf-8")
                resolver_input = Path(command[command.index("compile") + 1])
                observed_inputs["top"] = compiler._requirements(resolver_input)
                observed_inputs["gpu"] = compiler._requirements(
                    resolver_input.parent / "requirements-gpu.in"
                )
                observed_inputs["sdk"] = compiler._requirements(
                    resolver_input.parent / "requirements-serverless.in"
                )
                destination = Path(command[command.index("-o") + 1])
                destination.write_text(real_compiled_lock(), encoding="utf-8")
                return subprocess.CompletedProcess(command, 0)

            hostile_env = {
                **os.environ,
                "UV_INDEX": "https://evil.invalid/simple",
                "UV_DEFAULT_INDEX": "https://evil.invalid/simple",
                "UV_EXTRA_INDEX_URL": "https://evil.invalid/simple",
                "UV_TORCH_BACKEND": "cu130",
                "PIP_INDEX_URL": "https://evil.invalid/simple",
                "PIP_EXTRA_INDEX_URL": "https://evil.invalid/simple",
            }
            with patch.dict(os.environ, hostile_env, clear=True), patch(
                "scripts.compile_serverless_gpu_lock.subprocess.run",
                side_effect=fake_run,
            ):
                compiler.compile_lock("uv", input_path=source, output_path=output)

            command = observed_command
            env = observed_env
            self.assertIn("--no-config", command)
            self.assertIn("--no-annotate", command)
            self.assertIn("--no-emit-package", command)
            self.assertIn("torch", command)
            self.assertIn("--default-index", command)
            self.assertIn("https://pypi.org/simple", command)
            self.assertIn("--emit-index-url", command)
            self.assertIn("--link-mode", command)
            self.assertIn("copy", command)
            self.assertIn("--cache-dir", command)
            cache_dir = Path(command[command.index("--cache-dir") + 1])
            self.assertFalse(cache_dir.exists())
            self.assertFalse(any(key.startswith("UV_") for key in env))
            self.assertNotIn("PIP_INDEX_URL", env)
            self.assertNotIn("PIP_EXTRA_INDEX_URL", env)
            self.assertEqual(observed_inputs["top"], compiler.EXPECTED_TOP_LEVEL_REQUIREMENTS)
            self.assertEqual(observed_inputs["gpu"], compiler.EXPECTED_GPU_INPUT_REQUIREMENTS)
            self.assertEqual(
                observed_inputs["sdk"], compiler.EXPECTED_SERVERLESS_INPUT_REQUIREMENTS
            )
            final = output.read_text(encoding="utf-8")
            self.assertEqual(final.splitlines()[-1], EXPECTED_TORCH)
            self.assertEqual(final.count("torch @ "), 1)
            self.assertFalse(list(root.glob("*.lock.tmp")))
            self.assertFalse(list(root.glob(".serverless-input.*")))

    def test_invalid_generated_output_preserves_previous_lock_and_cleans_temp(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = write_valid_input_tree(root)
            output = root / "requirements.lock"
            output.write_text("previous-lock\n", encoding="utf-8")

            def fake_run(command, **kwargs):
                destination = Path(command[command.index("-o") + 1])
                destination.write_text("", encoding="utf-8")
                return subprocess.CompletedProcess(command, 0)

            with patch(
                "scripts.compile_serverless_gpu_lock.subprocess.run",
                side_effect=fake_run,
            ):
                with self.assertRaises(RuntimeError):
                    compiler.compile_lock("uv", input_path=source, output_path=output)

            self.assertEqual(output.read_text(encoding="utf-8"), "previous-lock\n")
            self.assertFalse(list(root.glob("*.lock.tmp")))
            self.assertFalse(list(root.glob(".serverless-input.*")))


class UvVersionTests(unittest.TestCase):
    def test_accepts_only_uv_0_13_4(self):
        accepted = subprocess.CompletedProcess(
            ["uv", "--version"], 0, stdout="uv 0.13.4 (a1b2c3d4 2026-01-01)\n"
        )
        rejected = subprocess.CompletedProcess(
            ["uv", "--version"], 0, stdout="uv 0.13.10\n"
        )
        with patch(
            "scripts.compile_serverless_gpu_lock.subprocess.run",
            return_value=accepted,
        ):
            self.assertEqual(compiler._uv_binary("uv"), "uv")
        with patch(
            "scripts.compile_serverless_gpu_lock.subprocess.run",
            return_value=rejected,
        ):
            with self.assertRaises(RuntimeError):
                compiler._uv_binary("uv")


