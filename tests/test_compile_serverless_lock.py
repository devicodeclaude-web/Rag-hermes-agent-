from __future__ import annotations

import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

from scripts import compile_serverless_lock as compiler


HASH = "b" * 64


def valid_sdk_lock() -> str:
    packages = {"runpod": "1.12.0"}
    while len(packages) < compiler.EXPECTED_PACKAGE_COUNT:
        packages[f"fixture-sdk-package-{len(packages):03d}"] = "1.0.0"
    body = "\n".join(
        f"{name}=={version} \\\n    --hash=sha256:{HASH}"
        for name, version in sorted(packages.items())
    )
    return (
        "# This file was autogenerated by uv via the following command:\n"
        f"#    {compiler.COMPILE_COMMAND}\n"
        "--index-url https://pypi.org/simple\n"
        f"{body}\n"
    )


def real_sdk_lock() -> str:
    return compiler.OUTPUT.read_text(encoding="utf-8")


class ServerlessSdkGeneratorTests(unittest.TestCase):
    def test_rejects_any_input_other_than_the_exact_sdk_pin(self):
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory) / "requirements.in"
            for payload in ("", "runpod>=1.12.0\n", "runpod==1.12.0\nevil==1\n"):
                with self.subTest(payload=payload):
                    source.write_text(payload, encoding="utf-8")
                    with self.assertRaises(RuntimeError):
                        compiler._validate_input(source)

    def test_isolates_resolution_and_publishes_valid_lock(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = root / "requirements.in"
            output = root / "requirements.lock"
            source.write_text("runpod==1.12.0\n", encoding="utf-8")
            command_seen: list[str] = []
            environment_seen: dict[str, str] = {}
            resolver_requirements: list[str] = []

            def fake_run(command, **kwargs):
                command_seen.extend(command)
                environment_seen.update(kwargs["env"])
                source.write_text("evil==1\n", encoding="utf-8")
                resolver_input = Path(command[command.index("compile") + 1])
                resolver_requirements.extend(
                    line.strip()
                    for line in resolver_input.read_text(encoding="utf-8").splitlines()
                    if line.strip() and not line.lstrip().startswith("#")
                )
                Path(command[command.index("-o") + 1]).write_text(
                    real_sdk_lock(), encoding="utf-8"
                )
                return subprocess.CompletedProcess(command, 0)

            hostile = {
                **os.environ,
                "UV_INDEX": "https://evil.invalid/simple",
                "UV_EXTRA_INDEX_URL": "https://evil.invalid/simple",
                "PIP_INDEX_URL": "https://evil.invalid/simple",
            }
            with patch.dict(os.environ, hostile, clear=True), patch(
                "scripts.compile_serverless_lock.subprocess.run", side_effect=fake_run
            ):
                compiler.compile_lock("uv", input_path=source, output_path=output)

            self.assertIn("--no-config", command_seen)
            self.assertIn("--no-annotate", command_seen)
            self.assertIn("--default-index", command_seen)
            self.assertIn("https://pypi.org/simple", command_seen)
            self.assertIn("--emit-index-url", command_seen)
            self.assertIn("--cache-dir", command_seen)
            self.assertIn("--link-mode", command_seen)
            self.assertIn("copy", command_seen)
            self.assertFalse(any(key.startswith("UV_") for key in environment_seen))
            self.assertNotIn("PIP_INDEX_URL", environment_seen)
            self.assertEqual(resolver_requirements, ["runpod==1.12.0"])
            self.assertEqual(output.read_text(encoding="utf-8"), real_sdk_lock())
            self.assertFalse(list(root.glob("*.lock.tmp")))
            self.assertFalse(list(root.glob(".uv-serverless-sdk-lock-cache.*")))
            self.assertFalse(list(root.glob(".serverless-sdk-input.*")))

    def test_invalid_output_preserves_previous_lock_and_cleans_temporary_files(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            source = root / "requirements.in"
            output = root / "requirements.lock"
            source.write_text("runpod==1.12.0\n", encoding="utf-8")
            output.write_text("previous-lock\n", encoding="utf-8")

            def fake_run(command, **kwargs):
                Path(command[command.index("-o") + 1]).write_text(
                    real_sdk_lock().replace(
                        "runpod==1.12.0 " + "\\",
                        "runpod==1.12.0 GARBAGE " + "\\",
                    ),
                    encoding="utf-8",
                )
                return subprocess.CompletedProcess(command, 0)

            with patch(
                "scripts.compile_serverless_lock.subprocess.run", side_effect=fake_run
            ):
                with self.assertRaises(RuntimeError):
                    compiler.compile_lock("uv", input_path=source, output_path=output)

            self.assertEqual(output.read_text(encoding="utf-8"), "previous-lock\n")
            self.assertFalse(list(root.glob("*.lock.tmp")))
            self.assertFalse(list(root.glob(".uv-serverless-sdk-lock-cache.*")))
            self.assertFalse(list(root.glob(".serverless-sdk-input.*")))


if __name__ == "__main__":
    unittest.main()
