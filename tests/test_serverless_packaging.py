from __future__ import annotations

from pathlib import Path
import sys
import tomllib
from types import SimpleNamespace
import unittest
from unittest.mock import patch

from scripts import runpod_serverless_handler as worker


ROOT = Path(__file__).resolve().parents[1]


class ServerlessPackagingTests(unittest.TestCase):
    def test_pyproject_pins_stable_runpod_sdk(self):
        payload = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
        extras = payload["project"]["optional-dependencies"]
        self.assertEqual(extras["serverless"], ["runpod==1.12.0"])

    def test_serverless_input_matches_extra_and_records_compile_target(self):
        content = (ROOT / "requirements-serverless.in").read_text(encoding="utf-8")
        self.assertIn("runpod==1.12.0", content.splitlines())
        self.assertIn("--python-platform x86_64-manylinux_2_28", content)
        self.assertIn("--python-version 3.12", content)
        self.assertIn("uv==0.13.4", content)
        self.assertIn("python -m scripts.compile_serverless_lock", content)
        self.assertIn("--no-config", content)
        self.assertIn("cache temporaire isolé", content)
        self.assertIn("requirements-serverless-gpu.lock.txt", content)

    def test_serverless_lock_pins_stable_sdk_with_hashes(self):
        content = (ROOT / "requirements-serverless.lock.txt").read_text(
            encoding="utf-8"
        )
        self.assertIn("runpod==1.12.0 \\", content)
        self.assertNotIn("runpod==2.0.0rc", content)
        self.assertIn("--hash=sha256:", content)
        self.assertEqual(
            content.splitlines()[:3],
            [
                "# This file was autogenerated by uv via the following command:",
                "#    python -m scripts.compile_serverless_lock",
                "--index-url https://pypi.org/simple",
            ],
        )

    def test_serverless_gpu_input_pins_official_torch_wheel(self):
        content = (ROOT / "requirements-serverless-gpu.in").read_text(
            encoding="utf-8"
        )
        torch_wheel = (
            "torch @ https://download-r2.pytorch.org/whl/cu128/"
            "torch-2.8.0%2Bcu128-cp312-cp312-manylinux_2_28_x86_64.whl"
            "#sha256=4354fc05bb79b208d6995a04ca1ceef6a9547b1c4334435574353d381c55087c"
        )
        requirements = [
            line
            for line in content.splitlines()
            if line and not line.startswith("#")
        ]
        self.assertEqual(
            requirements,
            [
                "-r requirements-gpu.in",
                "-r requirements-serverless.in",
                torch_wheel,
            ],
        )
        self.assertIn("--python-platform x86_64-manylinux_2_28", content)
        self.assertNotIn("--torch-backend", content)
        self.assertNotIn("--extra-index-url", content)
        self.assertIn("uv venv", content)
        self.assertIn(
            'uv venv "$verify_root/venv" --python 3.12 --no-python-downloads',
            content,
        )
        self.assertIn("uv pip install --python", content)
        self.assertIn("--dry-run --require-hashes", content)
        self.assertNotIn("--system", content)

    def test_serverless_gpu_lock_matches_expected_runtime(self):
        content = (ROOT / "requirements-serverless-gpu.lock.txt").read_text(
            encoding="utf-8"
        )
        torch_requirement = (
            "torch @ https://download-r2.pytorch.org/whl/cu128/"
            "torch-2.8.0%2Bcu128-cp312-cp312-manylinux_2_28_x86_64.whl"
            "#sha256=4354fc05bb79b208d6995a04ca1ceef6a9547b1c4334435574353d381c55087c"
        )
        self.assertIn(
            "python -m scripts.compile_serverless_gpu_lock",
            content.splitlines()[1],
        )
        self.assertEqual(
            [line for line in content.splitlines() if line.startswith("torch @ ")],
            [torch_requirement],
        )
        self.assertIn("triton==3.4.0 \\", content)
        self.assertIn("nvidia-cuda-runtime-cu12==12.8.90 \\", content)
        self.assertIn("runpod==1.12.0 \\", content)
        self.assertIn("flagembedding==1.3.5 \\", content)
        self.assertNotIn("torch==2.6.0 \\", content)
        self.assertNotIn("--torch-backend", content)
        self.assertNotIn("--extra-index-url", content)
        self.assertEqual(
            [line for line in content.splitlines() if line.startswith("--index-url ")],
            ["--index-url https://pypi.org/simple"],
        )
        self.assertIn("--hash=sha256:", content)

    def test_feasibility_intro_distinguishes_lock_from_runtime_validation(self):
        content = (ROOT / "docs/serverless-gpu-campaign-feasibility.md").read_text(
            encoding="utf-8"
        )
        introduction = content.split("## Faits vérifiés", maxsplit=1)[0]
        self.assertIn("lock combiné", introduction)
        self.assertIn("résolu", introduction)
        self.assertIn("installation sèche", introduction)
        self.assertIn("image Serverless n’a été construite", introduction)
        self.assertIn("runtime n’a été validé", introduction)
        self.assertIn("lock local revérifié le 2026-10-27", content)
        self.assertIn("Faits RunPod vérifiés le 2026-10-19", content)
        self.assertIn("runtime attendu", content)
        self.assertIn("n’attestent pas que `import torch` fonctionne", content)

    def test_main_registers_exact_handler_with_runpod_sdk(self):
        registrations = []
        fake_runpod = SimpleNamespace(
            serverless=SimpleNamespace(start=lambda config: registrations.append(config))
        )
        with patch.dict(sys.modules, {"runpod": fake_runpod}):
            worker.main()
        self.assertEqual(registrations, [{"handler": worker.handler}])


if __name__ == "__main__":
    unittest.main()
